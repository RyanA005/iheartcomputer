// keep canvas and context in global scope for ease
const canvas = document.getElementById("heart");
const ctx = canvas.getContext("2d");
const size = 300;
canvas.width = size 
canvas.height = size

// helpers
function clear() {
    ctx.fillStyle = "white";
    ctx.fillRect(0, 0, size, size);
}
function draw(p) {
    const s = 10;
    ctx.fillStyle = "red";
    ctx.fillRect(p.x - (s/2), p.y - (s/2), s, s);
}
function screen(p) {
    return {
        x: (p.x + 1) / 2 * size, 
        y: (1 - (p.y + 1) / 2) * size,
    }
}
function project({x, y, z}) {
    return {
        x: x / z, 
        y: y / z,
    }
}
function line(p1, p2) {
    ctx.lineWidth = 5
    ctx.strokeStyle = "red"
    ctx.beginPath()
    ctx.moveTo(p1.x, p1.y)
    ctx.lineTo(p2.x, p2.y)
    ctx.stroke()
}

// transformations and translations
function translate(p, dz) {
     return {
        x: p.x,
        y: p.y,
        z: p.z + dz,
     }
}
function rotate(p, a) {
    const s = Math.sin(a)
    const c = Math.cos(a)

     return {
        x: (p.x * c) - (p.z * s),
        y: (p.y),
        z: (p.x * s) + (p.z * c),
     }
}

